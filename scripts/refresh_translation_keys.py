"""Generate extraction declarations for dynamic category/form labels and Qt-free errors.
Does not edit Argon's TS translations. Run before lupdate after changing source labels.
"""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[1];keys=set();prefixes=set()
for file in (root/'src/core').glob('*.cpp'):
 for m in re.finditer(r'throw std::runtime_error\(("(?:[^"\\]|\\.)*")\s*(\+)?',file.read_text()):
  try:text=json.loads(m[1])
  except ValueError:continue
  keys.add(text)
  if m[2]:prefixes.add(text)
for file in (root/'src/ui').glob('*.cpp'):
 s=file.read_text()
 for value in re.findall(r'(?:background|libraryJob)\(\s*(?:this|parent|owner)\s*,\s*("(?:[^"\\]|\\.)*")',s):keys.add(json.loads(value))
 for group in re.findall(r'addItems\(\{(.*?)\}\)',s,re.S):
  for value in re.findall(r'"(?:[^"\\]|\\.)*"',group):keys.add(json.loads(value))
 for value in re.findall(r'(?:flag|number)\(f,\s*("(?:[^"\\]|\\.)*")',s):keys.add(json.loads(value))
text='// Generated by scripts/refresh_translation_keys.py; extraction only.\n#include <QCoreApplication>\nstatic const char* labels[]={\n'+''.join('QT_TRANSLATE_NOOP("Ensemble",'+json.dumps(k,ensure_ascii=False)+'),\n' for k in sorted(keys))+'};\n'
(root/'translations/catalog_keys.cpp').write_text(text)
(root/'translations/engine_prefixes.h').write_text('// Generated translation boundaries; paths/IDs stay unchanged.\n#pragma once\nnamespace reverie {inline constexpr const char* engineErrorPrefixes[]={\n'+''.join(json.dumps(k,ensure_ascii=False)+',\n' for k in sorted(prefixes,key=lambda value:(-len(value),value)))+'};}\n')
